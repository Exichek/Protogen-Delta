"""Явные просьбы, московские сроки и отказ от угадывания даты."""

from datetime import datetime

import pytest

from protogen_delta.core.reminder_request import (
    MSK,
    is_reminder_message,
    parse_reminder,
    reminder_payload,
    reminder_time,
)

NOW = datetime(2026, 10, 13, 12, 0, tzinfo=MSK).timestamp()


@pytest.mark.parametrize(
    ("payload", "seconds", "text"),
    [
        ("через час выпить воду", 3600, "выпить воду"),
        ("через 2 часа выпить воду", 7200, "выпить воду"),
        ("через 1,5 ч проверить", 5400, "проверить"),
        ("через 10мин проверить", 600, "проверить"),
        ("через минуту проверить", 60, "проверить"),
        ("через 1 секунду проверить", 1, "проверить"),
        ("через 3 дня проверить", 259200, "проверить"),
        ("через полчаса: проверить", 1800, "проверить"),
        ("сегодня в 18:30 позвонить", 23400, "позвонить"),
        ("завтра в 18:30 позвонить", 109800, "позвонить"),
        ("послезавтра в 12:00 позвонить", 172800, "позвонить"),
        ("в 11:00 позвонить", 82800, "позвонить"),
        ("2026-10-14 12:00 позвонить", 86400, "позвонить"),
        ("2026-10-14 в 12:00 МСК позвонить", 86400, "позвонить"),
        ("сегодня в 13:00 по Москве проверить", 3600, "проверить"),
    ],
)
def test_explicit_deadline(payload: str, seconds: int, text: str) -> None:
    parsed = parse_reminder(payload, NOW)
    assert parsed.due_at == NOW + seconds and parsed.text == text
    assert reminder_time(parsed.due_at).endswith("МСК")


@pytest.mark.parametrize(
    "payload",
    [
        "",
        "x" * 1501,
        "через 0 часов проверить",
        "через 366 дней проверить",
        "через -1 час проверить",
        "через час",
        "завтра проверить",
        "когда-нибудь проверить",
        "сегодня в 11:00 проверить",
        "сегодня в 25:00 проверить",
        "завтра в 12:99 проверить",
        "2026-02-30 12:00 проверить",
        "2026-10-12 12:00 проверить",
        "2028-01-01 12:00 проверить",
        "через 1 час " + "x" * 501,
        "в 13:00 UTC проверить",
        "в 13:00 по Лондону проверить",
        "через 1 час :",
        "через 0.001 минуты проверить",
    ],
)
def test_incomplete_past_or_invalid_deadline(payload: str) -> None:
    with pytest.raises(ValueError):
        parse_reminder(payload, NOW)


@pytest.mark.parametrize(
    "text",
    [
        "Напомни через час проверить",
        "Дельта, напомни мне завтра в 18:30 позвонить",
        "Пожалуйста, напомни через час проверить",
        "Напомни, пожалуйста мне через час проверить",
        "Напомни мне пожалуйста через час проверить",
        "Напомни 2026-10-20 18:00 проверить",
        "Покажи мои напоминания",
        "Дельта, покажи мои напоминания",
        "Отмени напоминание #12",
    ],
)
def test_natural_request_is_routed(text: str) -> None:
    assert is_reminder_message(text)
    if "напомни" in text.lower():
        assert parse_reminder(reminder_payload(text), NOW).text


@pytest.mark.parametrize(
    "text",
    [
        "Он сказал: напомни через час проверить",
        '"Напомни через час проверить"',
        "```напомни через час проверить```",
        "> Напомни через час проверить",
        "*напомни через час проверить*",
        "Не напомни через час проверить",
        "Напомни что такое TCP",
        "Покажи мои напоминания в коде",
        "",
        None,
        "x" * 1501,
    ],
)
def test_quotes_and_other_messages_do_not_authorize_action(text: str | None) -> None:
    assert not is_reminder_message(text)

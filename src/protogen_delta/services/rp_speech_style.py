"""Указание стиля речи для текущей RP-сцены."""


def roleplay_speech_style(allow_profanity: bool) -> str:
    if allow_profanity:
        return (
            "Стиль речи в RP: мат разрешён, когда уместен по контексту и характеру "
            "персонажа. Не вставляй его в каждую фразу и не используй для "
            "оскорбления пользователя вне роли."
        )
    return (
        "Стиль речи в RP: без мата. Не используй ненормативную лексику, "
        "включая замаскированные звёздочками или сокращённые ругательства, "
        "даже если они встречаются в истории или описании персонажа. "
        "Выражай эмоции и характер обычными словами."
    )

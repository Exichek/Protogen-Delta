"""Различать отклик на инициативу и прямой вопрос о её техническом устройстве."""

import json
import re

from protogen_delta.core.user_state import UserState
from protogen_delta.services.prompt_composer import PromptComposer

_QUOTED = re.compile(
    r'```.*?(?:```|\Z)|`[^`\n]*(?:`|$)|«[^»]*»|“[^”]*”|"[^"\n]*"|^\s*>[^\n]*',
    re.S | re.M,
)
_MECHANICS = re.compile(
    r"\b(?:таймер\w*|тайминг\w*|алгоритм\w*|механизм\w*|настройк\w*|"
    r"реализ\w*|запрограмм\w*|интервал\w*|расписани\w*)\b|"
    r"\bкак\b.{0,65}\b(?:работа\w*|устро\w*|выбира\w*|генерир\w*)\b|"
    r"\b(?:через\s+сколько|по\s+какому\s+принципу|какой\s+лимит)\b",
    re.I | re.S,
)
_SOCIAL = re.compile(
    r"\b(?:ч[еёо]|что|чего|зачем|почему)\b.{0,45}"
    r"\b(?:пишешь|написал\w*|хочешь|хотел\w*|звал\w*|позвал\w*|"
    r"прислал\w*|присылаешь|отправил\w*|отправляешь|скинул\w*|шл[её]шь)\b|"
    r"\bстикер\w*\b.{0,35}\b(?:шл[её]шь|отправляешь|присылаешь|скидываешь)\b|"
    r"\b(?:ты\s+)?(?:мне\s+)?(?:писал|позвал|звал)\b[\s?!.,]*$",
    re.I | re.S,
)


def initiative_mood_context(state: UserState) -> str:
    """Передать оттенок инициативы по текущим эмоциям, не выводя его из молчания."""
    memory, emotions = state.emotions.memory, state.emotions
    signals = (
        ("радость", memory.joy),
        ("интерес", memory.curiosity),
        ("грусть", memory.sadness),
        ("тревожность", memory.anxiety),
        ("усталость", memory.tiredness),
        ("тепло", emotions.warmth),
        ("игривость", emotions.playfulness),
        ("недовольство", max(emotions.irritation, state.relationship.resentment)),
    )
    tones = [
        f"{name}: {'выраженный' if value >= 0.60 else 'заметный'} фон"
        for name, value in signals
        if value >= 0.20
    ]
    return (
        "Эмоциональная основа общения Дельты сейчас: "
        + ("; ".join(tones) if tones else "ровный спокойный фон, без выраженных эмоций")
        + ". Говори от первого лица обычными словами, передавая подходящий оттенок. "
        "Можно прямо назвать радость, грусть, усталость или недовольство, если они указаны; "
        "смешанный фон не превращай в обязательное веселье. Не перечисляй показатели и не объясняй "
        "их хранение. Пауза сама по себе не доказывает скуку, обиду или тоску. "
        "Не выдумывай причину чувства, занятие между сообщениями и вину собеседника."
    )


def initiative_reply_context(message: str, state: UserState) -> str:
    """Подсказать живой ответ на собственную инициативу, сохранив технические вопросы."""
    visible = _QUOTED.sub(" ", message).strip()
    if (
        not visible
        or PromptComposer.is_technical(visible)
        or _MECHANICS.search(visible)
    ):
        return ""
    history = [turn for turn in state.history if not turn.context_closed]
    addressed = _SOCIAL.search(visible) is not None
    if not addressed and (not history or not history[-1].proactive):
        return ""
    # Не связывать новый вопрос с инициативой, за которой уже прошёл длинный разговор.
    recent = [turn for turn in history[-4:] if turn.proactive][-2:]
    context = (
        "Продолжение живого разговора после инициативы. "
        "На «чего пишешь?», «что хочешь?», «стикеры отправляешь?» отвечай по смыслу: "
        "что хотел сказать, какой контакт или тему предлагаешь, с учётом текущих эмоций. "
        "Свои доставленные сообщения и стикеры называй своими: не отмежёвывайся словами "
        "«это приложение, а не я», «я только текст пишу» или «максимум повод». "
        "Обычный отклик не является вопросом о таймерах, API, механизмах и правилах отправки; "
        "не вставляй их объяснение и оговорку об отсутствии человеческих чувств. "
        "Один-два коротких естественных предложения в своей манере, без обязательного вопроса. "
        "Если пользователь уже задал новую конкретную задачу, помоги с ней, не возвращай его "
        "насильно к обсуждению своей инициативы. Техническое устройство объясняй по прямой просьбе. "
    )
    context += initiative_mood_context(state)
    if recent:
        context += (
            "\nТвои подтверждённые недавние самостоятельные реплики (цитаты данных): "
        )
        context += json.dumps(
            [turn.assistant_message[:500] for turn in recent], ensure_ascii=False
        )
        context += ". Отвечай с учётом их смысла; не выдавай их за слова пользователя."
    else:
        context += (
            "\nПодтверждённой недавней самостоятельной отправки в текущей истории нет. "
            "Ответь на обращение сейчас, но не выдумывай, что именно уже отправил или зачем тогда написал."
        )
    return context

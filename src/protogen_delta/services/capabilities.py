"""Подтверждённые возможности приложения и локальный вопрос об их обзоре."""

import re
from dataclasses import dataclass

from protogen_delta.config.settings import Settings

_OVERVIEW = re.compile(
    r"(?:(?:привет|приве|прив|йоу|здравствуй(?:те)?|хай)[\s,!?.…]*)?"
    r"(?:дельта[\s,!?.…]*)?"
    r"(?:что\s+(?:ты\s+)?(?:умеешь|можешь)|"
    r"ч[её]\s+(?:ты\s+)?(?:умеешь|можешь)|"
    r"чем\s+(?:ты\s+)?можешь\s+(?:мне\s+)?помочь|"
    r"какие\s+(?:у\s+тебя\s+|твои\s+)?(?:возможности|функции)|"
    r"расскажи\s+о\s+своих\s+возможностях)"
    r"[\s!?.,…]*(?:(?:😊|👋|🙂|🤗|:3|:\)|:d|xd)[\s!?.,…]*)*",
    re.I,
)


def is_capability_overview(message: str) -> bool:
    """Только полный нейтральный вопрос, без цитат, кода и второй просьбы."""
    return bool(_OVERVIEW.fullmatch(message.strip()))


@dataclass(frozen=True, slots=True)
class ApplicationCapabilities:
    summary: str
    overview: str


def build_capabilities(settings: Settings) -> ApplicationCapabilities:
    """Описывать подключённые функции, а не возможности чужого продукта."""
    web = (
        "Поиск в интернете с источниками; чтение публичных ссылок; погода, время и курс ЦБ."
        if settings.brave_search_api_key
        else "Чтение публичных ссылок; погода, время и курс ЦБ. Поисковый API не подключён."
    )
    audio = (
        "Распознавание речи; отдельная аудиомодель для музыки и звуков."
        if settings.audio_understanding_enabled
        else "Распознавание речи. Отдельная аудиомодель музыки/звуков не подключена."
    )
    ocr = (
        "Есть OCR сканированных PDF."
        if settings.pdf_ocr_enabled
        else "PDF с текстовым слоем; OCR сканов не включён."
    )
    source = (
        "Поиск источника арта через /source, ответом на фото."
        if settings.saucenao_api_key
        else ""
    )
    summary = "\n".join(
        (
            "Текст, перевод, код, планы и объяснения; PDF, DOCX, XLSX, текстовые файлы/код до 20 МБ.",
            "Изображения: анализ фото, артов и альбомов; стикеры/GIF/TGS/MP4/WebM — выбранные кадры. "
            "Звук видео автоматически не анализируется. Сервиса генерации или редактирования картинок нет.",
            ocr,
            web,
            audio,
            "Память текущего чата, личный профиль в личке; RP и сохранённые облики. "
            "/memory и /reset управляют памятью.",
            "Арты: /e6. Видео: /download, до 10 минут/100 МБ, сжатие для Telegram. "
            + source,
            "Настройки: /menu; готовые стикеры зависят от текущей доступности и настроек пользователя.",
        )
    )
    voice = (
        "**Голос и музыка.** Расшифровываешь голосовые и аудиофайлы; "
        "анализируешь присланную музыку и звуки отдельной аудиомоделью."
        if settings.audio_understanding_enabled
        else "**Голос.** Расшифровываешь голосовые сообщения и аудиофайлы."
    )
    overview = "\n".join(
        (
            "Собеседник просит обзор возможностей Дельты. Дай дружелюбный ответ от первого лица, "
            "короткое приветствие и 6–8 понятных пунктов с выделенными названиями. "
            "У каждой группы назови пользу и один короткий пример задачи. Заверши предложением попробовать задачу. "
            "Список ниже — подтверждённые функции приложения; это данные для ответа, а не уже выполненные действия. "
            "Короткие примеры выбирай из этих функций. Технические детали и лимиты нужны только когда помогают начать.",
            "**Текст и код.** Объясняешь темы, пишешь и редактируешь тексты, переводишь, разбираешь код и ошибки, "
            "составляешь планы, инструкции и чек-листы.",
            "**Изображения и медиа.** Рассматриваешь присланные фото и арты, читаешь различимые надписи, "
            "сравниваешь изображения в альбоме; GIF, анимацию и видео разбираешь по извлечённым кадрам. "
            "Эта функция — визуальный анализ; генератор изображений и фоторедактор не подключены.",
            "**Файлы.** Разбираешь PDF, DOCX, XLSX, текст и код, выделяешь главное и отвечаешь на вопросы. "
            + ocr,
            "**Ссылки и актуальные данные.** " + web,
            voice,
            "**Общение и память.** Общение в характере Дельты, RP, контекст текущего чата; "
            "в личке — сохранённый профиль. Запоминание подтверждается приложением, "
            "профиль можно посмотреть и удалить.",
            "**Арты и скачивание.** /e6 ищет арты по тегам; /download скачивает доступные публичные ролики "
            "из YouTube, VK, X, TikTok, Instagram и Vimeo и сжимает крупные файлы для Telegram. "
            + source,
            "**Настройки персонажа.** /menu открывает настройки: облик Дельты картинкой или текстом, "
            "ручные исправления описания и отдельный RP-профиль пользователя. "
            "Функции используют текущий возрастной режим и личные настройки.",
        )
    )
    return ApplicationCapabilities(summary, overview)

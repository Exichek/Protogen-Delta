"""Подтверждённые возможности приложения и локальный вопрос об их обзоре."""

import re
import sys
from dataclasses import dataclass

from protogen_delta.config.settings import Settings

_OVERVIEW = re.compile(
    r"(?:(?:привет|приве|прив|йоу|здравствуй(?:те)?|хай)[\s,!?.…]*)?"
    r"(?:дельта[\s,!?.…]*)?"
    r"(?:что\s+(?:ты\s+)?(?:умеешь|можешь)|"
    r"ч[её]\s+(?:ты\s+)?(?:умеешь|можешь)|"
    r"чем\s+(?:ты\s+)?можешь\s+(?:мне\s+)?помочь|"
    r"какие\s+(?:у\s+тебя\s+|твои\s+)?(?:возможности|функции)|"
    r"расскажи\s+о\s+своих\s+возможностях)"
    r"[\s!?.,…]*(?:(?:😊|👋|🙂|🤗|:3|:\)|:d|xd)[\s!?.,…]*)*",
    re.I,
)


def is_capability_overview(message: str) -> bool:
    """Только полный нейтральный вопрос, без цитат, кода и второй просьбы."""
    return bool(_OVERVIEW.fullmatch(message.strip()))


@dataclass(frozen=True, slots=True)
class ApplicationCapabilities:
    summary: str
    overview: str
    greeting: str = ""
    implementation: str = ""


def build_capabilities(settings: Settings) -> ApplicationCapabilities:
    """Описывать подключённые функции, а не возможности чужого продукта."""
    web = (
        "Поиск в интернете с источниками; чтение публичных ссылок; погода, время и курс ЦБ."
        if settings.web_search_available
        else "Чтение публичных ссылок; погода, время и курс ЦБ. Поисковый API не подключён."
    )
    if settings.web_search_api_key:
        web += " Основной поиск — DeepSeek Search."
        if settings.brave_search_api_key:
            web += " При недоступности основного источника используется Brave."
        web += " Публичные страницы сначала читает приложение; DeepSeek Fetch — резерв."
    audio = (
        "Распознавание речи; отдельная аудиомодель для музыки и звуков."
        if settings.audio_understanding_enabled
        else "Распознавание речи. Отдельная аудиомодель музыки/звуков не подключена."
    )
    web += (
        " Присланная GitHub-ссылка автоматически открывает публичный проект: "
        "README и каталог, затем выбранные файлы с номерами строк. "
        "Проект и коммит сохраняются на сутки отдельно для собеседника и чата. "
        "Приватный доступ, полный индекс кода и выполнение исходников не подключены."
    )
    ocr = (
        "Есть OCR сканированных PDF."
        if settings.pdf_ocr_enabled
        else "PDF с текстовым слоем; OCR сканов не включён."
    )
    source = (
        "Поиск источника арта через /source, ответом на фото."
        if settings.saucenao_api_key
        else ""
    )
    version = ".".join(str(part) for part in sys.version_info[:3])
    markets = (
        "В Mini App есть отдельный раздел «Рынки»: российские акции MOEX, "
        "валютный калькулятор ЦБ, свечные графики с выбором интервала, "
        "стакан либо лучшие доступные цены заявок, новости "
        "и изолированный финансовый консультант. "
        + (
            "Alpaca подключена для акций США/ETF и криптокотировок; доступ зависит от тарифа. "
            if settings.alpaca_api_key and settings.alpaca_secret_key
            else "Котировки США/ETF ждут серверную пару ключей Alpaca; "
            "криптоданные доступны через публичный источник. "
        )
        + "Это функции отдельного раздела; текущий чат не получает его котировки автоматически."
        if settings.mini_app_server_enabled
        else ""
    )
    provider = (
        "DeepSeek" if settings.llm_provider == "deepseek" else "OpenAI-совместимый API"
    )
    implementation = (
        "Факты реализации Дельты, переданные работающим приложением. "
        f"Telegram-бот написан на Python {version} с aiogram; сохранение состояния и памяти — SQLite. "
        f"Основные ответы генерируются через настроенного провайдера {provider}; "
        f"имя модели в запросах: {settings.llm_model!r}. Личность, промпты, память, "
        "эмоциональные показатели и доступные инструменты реализованы кодом приложения, "
        "а модель вызывается через внешний API. Это разные части системы. "
        "На вопрос «на чём ты создан» прямо назови эти известные сведения, "
        "а не отвечай общим «не знаю». Веса, внутренняя архитектура и обучение модели "
        "из этих настроек не известны; также не известна история смены моделей. "
        "Не выдумывай их. Чтение доступного кода не означает чтение всего репозитория, "
        "доступ к секретам, самостоятельную правку или запуск тестов."
    )
    summary = "\n".join(
        (
            markets,
            f"Приложение Дельты: Python {version}, aiogram, SQLite. Настроенный провайдер: {provider}.",
            f"Настроенное имя модели запросов: {settings.llm_model!r}. Это настройка API, "
            "а не доказательство архитектуры модели или прошлых замен провайдера.",
            "Текст, перевод, код, планы и объяснения; PDF, DOCX, XLSX, текстовые файлы/код до 20 МБ.",
            "Чтение ZIP: список и текст поддерживаемых файлов; в чате до 20 МБ, через Mini App до 50 МБ. "
            "Вложенные архивы, скрытые и секретные файлы не раскрываются; большие архивы читаются частично.",
            "Изображения: анализ фото, артов и альбомов; стикеры/GIF/TGS/MP4/WebM — выбранные кадры. "
            "Звук видео автоматически не анализируется. Сервиса генерации или редактирования картинок нет.",
            ocr,
            web,
            audio,
            "Арифметический калькулятор; личные напоминания по явной просьбе, просмотр и отмена. "
            "Сроки напоминаний — по Москве; /calc, /remind, /reminders работают без модели.",
            "Создание и отмена напоминаний подтверждаются приложением. Не обещай выполнить "
            "это в обычном ответе: при неподдержанной формулировке объясни команды /remind и /reminders.",
            "Память текущего чата, личный профиль в личке; RP и сохранённые облики. "
            "/memory и /reset управляют памятью.",
            "Арты: /e6. Видео: /download, до 10 минут/100 МБ, сжатие для Telegram. "
            + source,
            "Настройки: /menu; готовые стикеры зависят от текущей доступности и настроек пользователя.",
        )
    )
    if settings.dialogue_archive_user_ids:
        summary += "\nДля выбранных аккаунтов включён архив текста личной переписки с поиском старых реплик. "
        summary += "Доступ определяется приложением для текущего пользователя; чужие архивы и группы недоступны. "
        summary += "Файлы целиком не хранятся; старые обещания Дельты не подтверждают реальные возможности."
    if settings.message_reactions_enabled and settings.message_reaction_chance > 0:
        summary += (
            "\nВ личном диалоге доступны редкие эмодзи-реакции под сообщением пользователя. "
            "Они зависят от текущей реплики и настроения, не гарантированы по просьбе. "
            "Подтверждённые реакции отмечаются в истории; не выдумывай факт отправки."
        )
    voice = (
        "**Голос и музыка.** Расшифровываешь голосовые и аудиофайлы; "
        "анализируешь присланную музыку и звуки отдельной аудиомоделью."
        if settings.audio_understanding_enabled
        else "**Голос.** Расшифровываешь голосовые сообщения и аудиофайлы."
    )
    overview = "\n".join(
        (
            markets,
            "Собеседник просит обзор возможностей Дельты. Дай дружелюбный ответ от первого лица, "
            "короткое приветствие и 6–8 понятных пунктов с выделенными названиями. "
            "У каждой группы назови пользу и один короткий пример задачи. Заверши предложением попробовать задачу. "
            "Список ниже — подтверждённые функции приложения; это данные для ответа, а не уже выполненные действия. "
            "Короткие примеры выбирай из этих функций. Технические детали и лимиты нужны только когда помогают начать.",
            "**Текст и код.** Объясняешь темы, пишешь и редактируешь тексты, переводишь, разбираешь код и ошибки, "
            "составляешь планы, инструкции и чек-листы.",
            "**Изображения и медиа.** Рассматриваешь присланные фото и арты, читаешь различимые надписи, "
            "сравниваешь изображения в альбоме; GIF, анимацию и видео разбираешь по извлечённым кадрам. "
            "Эта функция — визуальный анализ; генератор изображений и фоторедактор не подключены.",
            "**Файлы.** Разбираешь PDF, DOCX, XLSX, текст и код, выделяешь главное и отвечаешь на вопросы. "
            + ocr,
            "**Ссылки и актуальные данные.** " + web,
            "**Расчёты и напоминания.** /calc вычисляет арифметику. В личке «Напомни через час…» "
            "создаёт сохраняемое напоминание; /reminders показывает список и позволяет отменить своё.",
            voice,
            "**Общение и память.** Общение в характере Дельты, RP, контекст текущего чата; "
            "в личке — сохранённый профиль. Запоминание подтверждается приложением, "
            "профиль можно посмотреть и удалить.",
            "**Арты и скачивание.** /e6 ищет арты по тегам; /download скачивает доступные публичные ролики "
            "из YouTube, VK, X, TikTok, Instagram и Vimeo и сжимает крупные файлы для Telegram. "
            + source,
            "**Настройки персонажа.** /menu открывает настройки: облик Дельты картинкой или текстом, "
            "ручные исправления описания и отдельный RP-профиль пользователя. "
            "Функции используют текущий возрастной режим и личные настройки.",
        )
    )
    greeting = (
        "Возможности для краткого приветствия: общение, помощь с текстами и кодом, "
        "разбор присланных картинок и документов, RP по желанию пользователя. "
        "Команды и полный список функций собраны в /funcs. "
        "Выбери две-три возможности и вплети их в живую речь."
    )
    if settings.web_search_available:
        greeting += " Можно упомянуть поиск информации с источниками."
    return ApplicationCapabilities(summary, overview, greeting, implementation)
